#!/bin/bash

# Setup Memory System for Existing Project
# Usage: setup-project-memory.sh [project-name]

set -e

# Check for help flag
if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  echo "Setup Memory System for Existing Project"
  echo ""
  echo "Usage: setup-project-memory [project-name]"
  echo ""
  echo "Arguments:"
  echo "  project-name    Name of the project (defaults to current directory name)"
  echo ""
  echo "This script will:"
  echo "  - Initialize basic-memory system"
  echo "  - Set up Cursor MCP configuration"
  echo "  - Configure Foam for daily notes"
  echo "  - Create memories directory structure"
  echo "  - Set up project-specific memory files"
  echo ""
  echo "Examples:"
  echo "  setup-project-memory                    # Use current directory name"
  echo "  setup-project-memory my-awesome-project # Use specific project name"
  exit 0
fi

PROJECT_NAME="${1:-$(basename "$(pwd)")}"
PROJECT_ROOT="$(pwd)"

echo "🚀 Setting up memory system for project: $PROJECT_NAME"
echo "📁 Project root: $PROJECT_ROOT"

# 1. Initialize basic-memory
echo "📦 Initializing basic-memory..."
~/.local/bin/init-memory.sh

# 2. Create or update Cursor MCP config
echo "⚙️  Setting up Cursor MCP configuration..."
mkdir -p .cursor

if [[ -f .cursor/mcp.json ]]; then
  echo "📝 Found existing .cursor/mcp.json - checking for basic-memory..."
  if grep -q "basic-memory" .cursor/mcp.json; then
    echo "✅ basic-memory already configured"
  else
    echo "⚠️  basic-memory not found - you may need to add it manually"
    echo "   Add this to your .cursor/mcp.json:"
    echo '   "basic-memory": {'
    echo '     "command": "~/.local/bin/basic-memory.sh",'
    echo '     "args": []'
    echo '   }'
  fi
else
  echo "📝 Creating new .cursor/mcp.json..."
  cat > .cursor/mcp.json << EOF
{
  "mcpServers": {
    "basic-memory": {
      "command": "~/.local/bin/basic-memory.sh",
      "args": []
    }
  }
}
EOF
fi

# 3. Create or update Foam configuration
echo "📝 Setting up Foam for daily notes..."
mkdir -p .vscode

if [[ -f .vscode/settings.json ]]; then
  echo "📝 Found existing .vscode/settings.json - checking for Foam config..."
  if grep -q "foam.dailyNote" .vscode/settings.json; then
    echo "✅ Foam already configured"
  else
    echo "⚠️  Foam not configured - you may need to add it manually"
    echo "   Add these lines to your .vscode/settings.json:"
    echo '   "foam.dailyNote.filenameFormat": "YYYY-MM-DD",'
    echo '   "foam.dailyNote.directory": "memories/journal",'
    echo '   "foam.dailyNote.template": ".foam/templates/daily-note.md"'
  fi
else
  echo "📝 Creating new .vscode/settings.json..."
  cat > .vscode/settings.json << EOF
{
  "foam.dailyNote.filenameFormat": "YYYY-MM-DD",
  "foam.dailyNote.directory": "memories/journal",
  "foam.dailyNote.template": ".foam/templates/daily-note.md"
}
EOF
fi

# 4. Create Foam template
echo "📋 Creating daily note template..."
mkdir -p .foam/templates
cat > .foam/templates/daily-note.md << EOF
---
type: daily-note
category: journal
project: $PROJECT_NAME
created: {{date:YYYY-MM-DD}}
status: draft
tags: [daily-note, journal, {{date:YYYY}}]
---

# {{date:YYYY-MM-DD}} - Daily Notes

## 🎯 Today's Focus
<!-- What are you working on today? -->

## 📝 Notes & Thoughts
<!-- Jot down ideas, observations, problems -->

## 🐛 Issues & Bugs
<!-- Problems you encountered -->

## 💡 Ideas & Features
<!-- New ideas or feature requests -->

## ✅ Tasks & Todos
<!-- Things to do -->

## 🧠 Learnings
<!-- What did you learn today? -->

## 🔗 Links & References
<!-- Important links, conversations, decisions -->

## 📋 Tomorrow's Plan
<!-- What to work on next -->

---
_Generated by Foam daily note template_
EOF

# 5. Create initial project files
echo "📚 Creating initial project files..."

# Update _index.md with project-specific info
cat > memories/_index.md << EOF
# $PROJECT_NAME Memory System

## 🎯 Project Overview
<!-- Brief description of the project -->

## 📋 Quick Commands
- \`mem export-conversation\` - Export Cursor conversations
- \`mem process-daily\` - Process daily notes
- \`mem create-adr "title"\` - Create architecture decision record
- \`mem search "query"\` - Search memories

## 📁 Directory Structure
- \`knowledge/\` - Domain knowledge, patterns, facts
- \`plans/\` - Roadmaps, specifications, strategies
- \`issues/\` - Problems, bugs, questions
- \`decisions/\` - Architecture decision records (ADRs)
- \`tasks/\` - Action items, checklists
- \`conversations/\` - AI conversation exports
- \`journal/\` - Daily notes and lessons learned

## 🔄 Workflow
1. **Daily**: Use Option+D for daily notes
2. **Conversations**: Export important AI discussions
3. **Decisions**: Create ADRs for architectural choices
4. **Knowledge**: Document patterns and solutions
5. **Issues**: Track problems and solutions

## 🎯 Project-Specific Notes
<!-- Add project-specific information here -->
EOF

# 6. Create initial project files
echo "📄 Creating initial project files..."

# Project intent
cat > memories/plans/intent.md << EOF
---
type: plan
category: project-intent
project: $PROJECT_NAME
created: $(date +"%Y-%m-%d")
status: draft
tags: [intent, project, overview]
---

# Project Intent

## 🎯 Purpose
<!-- What is this project trying to achieve? -->

## 🚀 Goals
<!-- What are the main goals? -->

## 📋 Success Criteria
<!-- How do we know we've succeeded? -->

## 🔄 Current Status
<!-- What's the current state? -->
EOF

# Project roadmap
cat > memories/plans/roadmap.md << EOF
---
type: plan
category: roadmap
project: $PROJECT_NAME
created: $(date +"%Y-%m-%d")
status: draft
tags: [roadmap, planning, milestones]
---

# Project Roadmap

## 🎯 Milestones
<!-- Major milestones and deadlines -->

## 📋 Current Sprint
<!-- What are we working on now? -->

## 🔄 Next Steps
<!-- What's coming up next? -->

## 🚧 Blockers
<!-- What's blocking progress? -->
EOF

# Next tasks
cat > memories/tasks/next.md << EOF
---
type: task
category: next-steps
project: $PROJECT_NAME
created: $(date +"%Y-%m-%d")
status: pending
tags: [tasks, next, todo]
---

# Next Tasks

## 🔥 High Priority
<!-- Urgent tasks -->

## 📋 Medium Priority
<!-- Important but not urgent -->

## 💡 Low Priority
<!-- Nice to have -->

## ✅ Completed
<!-- Recently completed tasks -->
EOF

echo ""
echo "✅ Memory system setup complete for $PROJECT_NAME!"
echo ""
echo "🎯 Next Steps:"
echo "1. Restart Cursor to pick up MCP configuration"
echo "2. Use Option+D to create daily notes"
echo "3. Use 'mem export-conversation' to save AI discussions"
echo "4. Use 'mem process-daily' to analyze daily notes"
echo ""
echo "📚 Available Commands:"
echo "- mem export-conversation"
echo "- mem process-daily"
echo "- mem create-adr \"title\""
echo "- mem search \"query\""
echo "- mem list [type]"
echo ""
echo "🔗 GitHub Integration:"
echo "- If .github/ directory exists, issues will be created as GitHub Issues"
echo "- Otherwise, issues are stored locally in memories/issues/"
